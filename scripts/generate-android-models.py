"""Generate the Android DTO subset from the checked-in OpenAPI contract."""
import argparse
import json
from pathlib import Path
root = Path(__file__).resolve().parents[1]
schemas = json.loads((root / 'shared/api/openapi-v1.json').read_text())['components']['schemas']
names = ['ServerInfo', 'LoginRequest', 'UserIdentity', 'MediaSummary', 'MediaDetails', 'MediaPage', 'LibraryBrowse', 'ProgressState', 'ProgressUpdate', 'TrackCatalog', 'MediaTrack', 'PlaybackPlan', 'SessionInfo', 'ClientCapabilities', 'PlaybackError']
def typ(prop):
    if '$ref' in prop:
        return prop['$ref'].split('/')[-1]
    kind = prop['type']; nullable = isinstance(kind, list) and 'null' in kind
    if isinstance(kind, list): kind = next(k for k in kind if k != 'null')
    value = {'string': 'String', 'boolean': 'Boolean', 'number': 'Double', 'integer': 'Long' if prop.get('format') == 'int64' else 'Int', 'array': 'List'}.get(kind)
    if value is None: raise ValueError(prop)
    if kind == 'array': value += '<' + typ(prop['items']) + '>'
    return value + ('?' if nullable else '')
out = '// Generated by scripts/generate-android-models.py; do not edit.\npackage org.splortch.mediaserver.core\n\nimport kotlinx.serialization.Serializable\n\n'
for name in names:
    schema = schemas[name]; fields = []
    for field, prop in schema['properties'].items():
        t = typ(prop); default = ''
        if field not in schema.get('required', []):
            if 'default' in prop: default = ' = ' + json.dumps(prop['default'])
            elif t.endswith('?'): default = ' = null'
            else: raise ValueError((name, field))
        fields.append(f'    val {field}: {t}{default}')
    out += '@Serializable\ndata class ' + name + '(\n' + ',\n'.join(fields) + '\n)'
    if name == 'LoginRequest': out += ' {\n    override fun toString() = "LoginRequest([redacted])"\n}'
    out += '\n\n'
p = root / 'clients/android/core/src/main/java/org/splortch/mediaserver/core/Models.kt'
if argparse.ArgumentParser().parse_known_args()[1] == ['--check']:
    if not p.exists() or p.read_text() != out: raise SystemExit('Android API models differ; run python scripts/generate-android-models.py')
else:
    p.parent.mkdir(parents=True, exist_ok=True); p.write_text(out)
