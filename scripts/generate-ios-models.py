"""Generate the iOS Codable model closure from the API v1 snapshot."""
import argparse
import json
from pathlib import Path

root = Path(__file__).resolve().parents[1]
schemas = json.loads((root / 'shared/api/openapi-v1.json').read_text())['components']['schemas']
names = set()
def typ(prop):
    if 'oneOf' in prop:
        return typ(next(p for p in prop['oneOf'] if p.get('type') != 'null')) + '?'
    if '$ref' in prop:
        name = prop['$ref'].split('/')[-1]
        collect(name)
        return name
    kind = prop['type']
    nullable = isinstance(kind, list)
    if nullable:
        kind = next(k for k in kind if k != 'null')
    value = {'string': 'String', 'integer': 'Int64' if prop.get('format') == 'int64' else 'Int',
             'number': 'Double', 'boolean': 'Bool', 'array': ''}[kind]
    if kind == 'array':
        value = '[' + typ(prop['items']) + ']'
    return value + ('?' if nullable else '')
def collect(name):
    if name in names:
        return
    names.add(name)
    for prop in schemas[name]['properties'].values():
        typ(prop)
for name in ['ServerInfo', 'LoginRequest', 'UserIdentity', 'MediaSummary', 'MediaDetails', 'ProgressState', 'ProgressUpdate']:
    collect(name)
out = '// Generated by scripts/generate-ios-models.py; do not edit.\nimport Foundation\n\n'
for name in sorted(names):
    fields = []
    for field, prop in schemas[name]['properties'].items():
        t = typ(prop)
        if field not in schemas[name].get('required', []) and not t.endswith('?'):
            t += '?'
        fields.append((field, t))
    out += f'public struct {name}: Codable, Sendable {{\n'
    out += ''.join(f'    public let {field}: {t}\n' for field, t in fields)
    out += '    public init(' + ', '.join(f'{f}: {t}' for f, t in fields) + ') {\n'
    out += ''.join(f'        self.{f} = {f}\n' for f, _ in fields)
    out += '    }\n}\n\n'
p = root / 'clients/ios/Sources/MediaCore/Models.swift'
parser = argparse.ArgumentParser()
parser.add_argument('--check', action='store_true')
if parser.parse_args().check:
    if not p.exists() or p.read_text() != out:
        raise SystemExit('Run python scripts/generate-ios-models.py')
else:
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(out)
